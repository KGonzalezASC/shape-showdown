function materializeBrandPlan(): NameDropPlan {
  const lines = ['SHAPE', 'SHOWDOWN'];
  const pieces: NameDropPiece[] = SHAPE_SHOWDOWN_PIECES.map(([type, rotation, x, y, delayMs, durationMs]) => ({
    type,
    rotation,
    x,
    y,
    cells: SHAPES[type][rotation].map(([dx, dy]) => ({ x: x + dx, y: y + dy })),
    delayMs,
    durationMs,
  }));

  return {
    name: 'SHAPE SHOWDOWN',
    lines,
    targetCells: nameTargetCells(lines),
    pieces,
    totalDurationMs: 16_026,
  };
}

const BRAND_PLANS: Record<string, NameDropPlan> = {
  'SHAPE SHOWDOWN': materializeBrandPlan(),
};

export function getPrebakedNameDropPlan(name: string): NameDropPlan | undefined {
  return BRAND_PLANS[name];
}
